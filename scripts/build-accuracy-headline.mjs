#!/usr/bin/env node
/**
 * build-accuracy-headline.mjs — generate src/lib/accuracy-headline.ts, the
 * single place the site states how accurate the model is.
 *
 * WHY THIS IS GENERATED
 * The global nav carried "May 2024 backtest · 5.7pp MAE" on all 3,947 pages.
 * The claim was true and it was the most flattering number available: a
 * backtest of an election the model was built against. The out-of-sample
 * record on the election the nav item actually points at is roughly double
 * that error. Hand-written accuracy copy drifts towards whichever number
 * flatters, so the numbers are generated from the ledgers and the nav reads
 * whatever they currently say.
 *
 * The three records are NOT interchangeable and the file keeps them apart:
 *   backtest      May 2024, scored after the fact against an election the
 *                 model had sight of. The weakest evidence of the three.
 *   out_of_sample May 2026, forecast published and sha256-witnessed BEFORE
 *                 polls opened, then scored against the count. This is the
 *                 headline, because it is the only one nobody can tune.
 *   running       Council by-elections since May 2025, regraded nightly as
 *                 results land, so it moves. Never hard-code it anywhere.
 *
 * Run from scripts/refresh-pipeline.mjs, or by hand after a results ingest.
 */
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { dirname, resolve, join } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const REPO = resolve(__dirname, "..");
const OUT = join(REPO, "src/lib/accuracy-headline.ts");

const readJson = (p) => JSON.parse(readFileSync(join(REPO, p), "utf8"));
const pp = (x) => Math.round(x * 1000) / 10; // proportion -> pp, 1dp
const pct = (x) => Math.round(x * 1000) / 10;

function main() {
  const postaudit = readJson("data/transparency/may-2026-postaudit-2026-05-10.json");
  const s = postaudit.prereg?.summary;
  if (!s) throw new Error("May 2026 postaudit has no prereg.summary block");

  const metaPath = "data/contests/local-byelections/_meta.json";
  const recent = existsSync(join(REPO, metaPath))
    ? readJson(metaPath).backtest?.recent
    : null;

  const bt = existsSync(join(REPO, "data/backtests/may-2024-summary.json"))
    ? readJson("data/backtests/may-2024-summary.json")
    : null;
  const btMae = bt?.overall_mae?.major_parties_avg ?? null;
  const btWinner = bt?.winner_accuracy ?? null;

  const outOfSample = {
    label: "May 2026 locked forecast",
    ballots: s.ballots_evaluated,
    winnerAccuracyPct: pct(s.winner_accuracy),
    maePp: pp(s.major_party_mae_avg),
  };
  const running = recent
    ? {
        label: "Council by-elections since May 2025",
        contests: recent.n,
        winnerAccuracyPct: pct(recent.winner_called_pct),
        maePp: Math.round(recent.mae_pp * 10) / 10,
      }
    : null;

  const body = `// GENERATED by scripts/build-accuracy-headline.mjs. Do not edit by hand.
//
// The site's accuracy claims, in one place, so no page can quote a kinder
// number than the record supports. Regenerate after any results ingest.
//
// Read the distinction before using these:
//   outOfSample  published and hash-witnessed BEFORE the count, then scored.
//                This is the honest headline and the one to lead with.
//   running      regraded nightly as by-election results land, so it moves.
//   backtest     scored against an election the model was built against.
//                Context only. It must never be the headline figure.

export interface AccuracyRecord {
  label: string;
  winnerAccuracyPct: number;
  maePp: number;
}

export const ACCURACY_OUT_OF_SAMPLE = ${JSON.stringify(outOfSample, null, 2)} as const;

export const ACCURACY_RUNNING = ${JSON.stringify(running, null, 2)} as const;

export const ACCURACY_BACKTEST_2024 = ${btMae != null ? JSON.stringify({
    label: "May 2024 backtest",
    winnerAccuracyPct: pct(btWinner),
    maePp: pp(btMae),
  }, null, 2) : "null"} as const;

/** One line for the nav and meta descriptions. Leads with the hardest number. */
export const ACCURACY_HEADLINE =
  "May 2026 out-of-sample: ${outOfSample.winnerAccuracyPct}% of winners, ${outOfSample.maePp}pp MAE";
`;

  writeFileSync(OUT, body);
  console.log(`Wrote ${OUT}`);
  console.log(`  out-of-sample : ${outOfSample.winnerAccuracyPct}% winners, ${outOfSample.maePp}pp MAE over ${outOfSample.ballots} ballots`);
  if (running) {
    console.log(`  running       : ${running.winnerAccuracyPct}% winners, ${running.maePp}pp MAE over ${running.contests} by-elections`);
  }
  console.log(`  2024 backtest : ${btMae != null ? pct(btWinner) + "% winners, " + pp(btMae) + "pp MAE" : "not found"} (context only)`);
}

main();
